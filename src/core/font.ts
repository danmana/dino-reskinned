export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const GLYPH_ADV = 6;

const cache = new Map<string, boolean[][]>();
function glyph(ch: string): boolean[][] {
  const key = G[ch] ? ch : G[ch.toUpperCase()] ? ch.toUpperCase() : '?';
  let g = cache.get(key);
  if (!g) {
    g = G[key].split('|').map((row) => row.split('').map((c) => c === '#'));
    cache.set(key, g);
  }
  return g;
}

export function textWidth(s: string, spacing = 1): number {
  if (!s.length) return 0;
  return s.length * (GLYPH_W + spacing) - spacing;
}

/** Draws text into a PixelBuffer. Returns the width drawn. */
export function drawText(buf: PixelBuffer, s: string, x: number, y: number, color: string, spacing = 1): number {
  const c = pack(color);
  let cx = x;
  for (const ch of s) {
    const g = glyph(ch);
    for (let gy = 0; gy < GLYPH_H; gy++) for (let gx = 0; gx < GLYPH_W; gx++) if (g[gy][gx]) buf.set(cx + gx, y + gy, c);
    cx += GLYPH_W + spacing;
  }
  return cx - x - spacing;
}

export function textBuffer(s: string, color: string, spacing = 1): PixelBuffer {
  const b = new PixelBuffer(Math.max(1, textWidth(s, spacing)), GLYPH_H);
  drawText(b, s, 0, 0, color, spacing);
  return b;
}

/** SVG markup (rects in currentColor) for crisp, themeable pixel text in the DOM. */
export function textSvg(s: string, spacing = 1): string {
  const w = textWidth(s, spacing);
  const rects: string[] = [];
  let cx = 0;
  for (const ch of s) {
    const g = glyph(ch);
    for (let gy = 0; gy < GLYPH_H; gy++) {
      let run = -1;
      for (let gx = 0; gx <= GLYPH_W; gx++) {
        const on = gx < GLYPH_W && g[gy][gx];
        if (on && run < 0) run = gx;
        if (!on && run >= 0) {
          rects.push(`<rect x="${cx + run}" y="${gy}" width="${gx - run}" height="1"/>`);
          run = -1;
        }
      }
    }
    cx += GLYPH_W + spacing;
  }
  return `<svg viewBox="0 0 ${w} ${GLYPH_H}" xmlns="http://www.w3.org/2000/svg" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects.join('')}</svg>`;
}
